/// Anything that can serve a route: every `async fn(&mut Ctx) -> Result` qualifies.
pub trait Action: Send + Sync + 'static {
    fn call<'a>(&'a self, c: &'a mut Ctx) -> BoxFuture<'a, Result>;
}

impl<F> Action for F
where
    F: for<'a> ember_kit::ActionFn<'a>,
{
    fn call<'a>(&'a self, c: &'a mut Ctx) -> BoxFuture<'a, Result> {
        Box::pin(ember_kit::ActionFn::call(self, c))
    }
}

pub struct Route {
    pub verb: Method,
    /// The Rails path spec, e.g. `/rooms/:room_id/messages(.:format)`. Compiled into `regex`; kept
    /// for the test that compares the table with `bin/rails routes`.
    #[cfg_attr(not(test), allow(dead_code))]
    pub pattern: &'static str,
    /// `controller#action`, as `bin/rails routes` prints it.
    pub endpoint: &'static str,
    pub defaults: &'static [(&'static str, &'static str)],
    action: Arc<dyn Action>,
    regex: Regex,
    names: Vec<String>,
}

impl Route {
    fn new(verb: Method, pattern: &'static str, endpoint: &'static str, action: impl Action) -> Self {
        let (regex, names) = compile(pattern);
        Self { verb, pattern, endpoint, defaults: &[], action: Arc::new(action), regex, names }
    }

    fn defaults(mut self, defaults: &'static [(&'static str, &'static str)]) -> Self {
        self.defaults = defaults;
        self
    }

    pub fn controller(&self) -> &'static str {
        self.endpoint.split_once('#').map_or(self.endpoint, |(controller, _)| controller)
    }

    pub fn action_name(&self) -> &'static str {
        self.endpoint.split_once('#').map_or("", |(_, action)| action)
    }
}

/// The route that matched the current request (`request.path_parameters` plus the endpoint),
/// available to actions as `c.current::<MatchedRoute>()`.
#[derive(Debug, Clone)]
pub struct MatchedRoute {
    pub endpoint: &'static str,
}

fn get(pattern: &'static str, endpoint: &'static str, action: impl Action) -> Route {
    Route::new(Method::GET, pattern, endpoint, action)
}

fn post(pattern: &'static str, endpoint: &'static str, action: impl Action) -> Route {
    Route::new(Method::POST, pattern, endpoint, action)
}

fn patch(pattern: &'static str, endpoint: &'static str, action: impl Action) -> Route {
    Route::new(Method::PATCH, pattern, endpoint, action)
}

fn put(pattern: &'static str, endpoint: &'static str, action: impl Action) -> Route {
    Route::new(Method::PUT, pattern, endpoint, action)
}

fn delete(pattern: &'static str, endpoint: &'static str, action: impl Action) -> Route {
    Route::new(Method::DELETE, pattern, endpoint, action)
}

